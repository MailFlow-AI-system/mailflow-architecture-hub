import type { ArchitecturePhase } from '../../../domain/architecture';
import type {
  ArchitectureDiagramDefinition,
  ArchitectureDiagramEdge,
  ArchitectureDiagramNode,
} from './types';

type NodeExtras = Pick<
  ArchitectureDiagramNode,
  'serviceId' | 'stackIds' | 'trustBoundaryIds' | 'group'
>;

type EdgeExtras = Pick<
  ArchitectureDiagramEdge,
  'trustBoundaryId' | 'confidentialData' | 'prohibited'
>;

function node(
  id: string,
  label: string,
  kind: ArchitectureDiagramNode['kind'],
  phases: ArchitecturePhase[],
  description: string,
  decisionIds: string[],
  extras: NodeExtras = {},
): ArchitectureDiagramNode {
  return { id, label, kind, phases, description, decisionIds, ...extras };
}

function edge(
  id: string,
  source: string,
  target: string,
  label: string,
  type: ArchitectureDiagramEdge['type'],
  phases: ArchitecturePhase[],
  decisionIds: string[],
  extras: EdgeExtras = {},
): ArchitectureDiagramEdge {
  return { id, source, target, label, type, phases, decisionIds, ...extras };
}

function view(definition: ArchitectureDiagramDefinition): ArchitectureDiagramDefinition {
  return definition;
}

